import { interviewReportModel } from "../models/interviewReport.model.js";
import {PDFParse} from "pdf-parse"
import {generateInterviewReportFromAi,generateResumePdf} from "../services/ai.service.js";

export const generateInterviewReport=async(req,res)=>{
    try {
        const userId=req.user.id
        const resumeFile=req.file
        const {jobDescription,selfDescription}=req.body
        const resumeContent=await (new PDFParse(Uint8Array.from(req.file.buffer))).getText()

        const interviewReportByAi=await generateInterviewReportFromAi({
            resume:resumeContent.text,
            selfDescription,
            jobDescription
        })

        console.log("Interview Report generated by AI:",interviewReportByAi);
        

        const interviewReport = await interviewReportModel.create({
            user:userId,
            selfDescription,
            jobDescription,
            resume:resumeContent.text,
            ...interviewReportByAi
        })

        res.status(201).json({
            message:"Interview Report generated successfully",
            interviewReport
        })
    } catch (error) {
        console.log(error);
    }
}

export const getInteviewReportById=async(req,res)=>{
    try {
        const interviewId=req.params.interviewId
        console.log("Fetching interview report with ID:", interviewId);
        const interviewReport=await interviewReportModel.findById(interviewId)

        if (!interviewReport){
            res.status(400).json({
                message:"Invalid Interview Id"
            })
        }
        
        res.status(200).json({
            message:"Interview Report fetched successfully",
            interviewReport
        })

    } catch (error) {
        console.log(error);
    }
}

/** 
 * @description Controller to get all interview reports of logged in user.
 */
export const getAllInterviewReportsController = async(req, res)=> {
    const interviewReports = await interviewReportModel.find({ user: req.user.id }).sort({ createdAt: -1 }).select("-resume -selfDescription -jobDescription -__v -technicalQuestions -behaviouralQuestions -skillGaps -preparationPlan")

    res.status(200).json({
        message: "Interview reports fetched successfully.",
        interviewReports
    })
}

export const generateResumePdfController=async(req,res)=>{
    const {interviewReportId}=req.params
    console.log("Generating PDF for interview report with ID:", interviewReportId);
    
    const interviewReport=await interviewReportModel.findById(interviewReportId)

    if (!interviewReport){
        return res.status(404).json({
            message:"Invalid Interview Report Id"
        })
    }
    const {resume,selfDescription,jobDescription}=interviewReport

    const pdfBuffer=await generateResumePdf({resume,selfDescription,jobDescription})

    res.set({
        "Content-Type":"application/pdf",
        "Content-Disposition":`attachment; filename=resume_${interviewReportId}.pdf`
    })

    res.send(pdfBuffer)
}

export const deleteInterviewReportController=async(req,res)=>{
    try {
        const { interviewId } = req.params;
        const report = await interviewReportModel.findOneAndDelete({ 
            _id: interviewId, 
            user: req.user.id 
        });

        if (!report) {
            return res.status(404).json({ message: "Report not found or unauthorized" });
        }

        res.status(200).json({ message: "Report deleted successfully" });
    } catch (error) {
        res.status(500).json({ message: "Server error during deletion" });
    }
};
